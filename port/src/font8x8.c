static uint8_t glyphs[GLYPHS][8];
static const uint8_t blank[8];

void font8x8_init(void)
{
    for (int g = 0; g < GLYPHS; g++) {
        const char *const *rows = blocks[g / GLYPHS_PER_BLOCK];
        int col0 = (g % GLYPHS_PER_BLOCK) * 9;
        for (int r = 0; r < 8; r++) {
            uint8_t bits = 0;
            for (int c = 0; c < 8; c++) {
                if (rows[r][col0 + c] == '#')
                    bits |= 0x80 >> c;
            }
            glyphs[g][r] = bits;
        }
    }
}

const uint8_t *font8x8_glyph(uint8_t ch)
{
    if (ch < FIRST_CHAR || ch >= FIRST_CHAR + GLYPHS)
        return blank;
    return glyphs[ch - FIRST_CHAR];
}
